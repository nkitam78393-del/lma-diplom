EMU_PER_PX = 9525          # 96 dpi
MAX_WIDTH_PX = 620         # ширина полосы набора


def screen_block(filename: str, number: str, title: str, idx: int, media: list) -> str:
    path = os.path.join(SCREENS, filename)
    with Image.open(path) as im:
        w, h = im.size
    scale = min(1.0, MAX_WIDTH_PX / w)
    cx, cy = int(w * scale * EMU_PER_PX), int(h * scale * EMU_PER_PX)
    media.append((f"rIdImg{idx}", filename, open(path, "rb").read()))
    body = pic(f"rIdImg{idx}", cx, cy, doc_pr_id=idx + 10, name=title)
    return body + caption(f"Рисунок {number} — {title}")


